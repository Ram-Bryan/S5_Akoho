    private String convertTheme(String idTheme) {
        if (idTheme == null) {
            return "blue";
        }
        switch (idTheme.trim()) {
            case "THM0001": {
                return "blue";
            }
            case "THM0002": {
                return "red";
            }
            case "THM0003": {
                return "yellow";
            }
            case "THM0004": {
                return "green";
            }
            case "THM0005": {
                return "purple";
            }
        }
        return "blue";
    }
