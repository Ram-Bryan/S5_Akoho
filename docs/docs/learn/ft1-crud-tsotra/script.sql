-- ============ Feature 1: LIVRE ============
CREATE SEQUENCE SEQ_LIVRE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE OR REPLACE FUNCTION getseq_livre RETURN NUMBER IS
  v_seq NUMBER;
BEGIN
  SELECT SEQ_LIVRE.NEXTVAL INTO v_seq FROM DUAL;
  RETURN v_seq;
END;
/
CREATE TABLE LIVRE (
    ID                VARCHAR2(50)   PRIMARY KEY,
    TITRE             VARCHAR2(500)  NOT NULL,
    AUTEUR            VARCHAR2(255),
    ISBN              VARCHAR2(50),
    ANNEEPUBLICATION  NUMBER(4),
    EDITEUR           VARCHAR2(255),
    PRIX              NUMBER(18,2),
    ETAT              NUMBER(2)      DEFAULT 1,
    IDUSER            VARCHAR2(50)   DEFAULT '0'
);

-- ============ Feature 2: MAISON + PIECE ============
CREATE SEQUENCE SEQ_MAISON START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE OR REPLACE FUNCTION getseq_maison RETURN NUMBER IS
  v_seq NUMBER;
BEGIN
  SELECT SEQ_MAISON.NEXTVAL INTO v_seq FROM DUAL;
  RETURN v_seq;
END;
/
CREATE TABLE MAISON (
    ID                VARCHAR2(50)   PRIMARY KEY,
    NOM               VARCHAR2(255)  NOT NULL,
    ADRESSE           VARCHAR2(500),
    VILLE             VARCHAR2(100),
    CODEPOSTAL        VARCHAR2(20),
    SURFACE           NUMBER(10,2),
    ANNECONSTRUCTION  NUMBER(4),
    ETAT              NUMBER(2)      DEFAULT 1,
    IDUSER            VARCHAR2(50)   DEFAULT '0'
);

CREATE SEQUENCE SEQ_PIECE START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE OR REPLACE FUNCTION getseq_piece RETURN NUMBER IS
  v_seq NUMBER;
BEGIN
  SELECT SEQ_PIECE.NEXTVAL INTO v_seq FROM DUAL;
  RETURN v_seq;
END;
/
CREATE TABLE PIECE (
    ID          VARCHAR2(50)   PRIMARY KEY,
    IDMERE      VARCHAR2(50)   NOT NULL,
    NOM         VARCHAR2(255),
    SUPERFICIE  NUMBER(10,2),
    ETAGE       NUMBER(2),
    TYPEPIECE   VARCHAR2(50),
    ETAT        NUMBER(2)      DEFAULT 1,
    IDUSER      VARCHAR2(50)   DEFAULT '0',
    CONSTRAINT FK_PIECE_MAISON FOREIGN KEY (IDMERE) REFERENCES MAISON(ID)
);

 COMMIT;

-- Sanity check: view must see the new columns
SELECT table_name, column_name, data_type, column_id
  FROM LISTECOLONNETABLE
 WHERE table_name IN ('LIVRE','MAISON','PIECE')
 ORDER BY table_name, column_id;

